use serde_json::Value;
use std::collections::BTreeSet;

const COMMANDS: [&str; 5] = [
    "session_get",
    "session_set",
    "session_patch",
    "session_flush",
    "session_read_terminal_scrollback",
];

#[test]
fn session_capability_is_restricted_to_its_commands_and_main_window() {
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/session-commands.json")).unwrap();
    let actual = capability["permissions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|permission| permission.as_str().unwrap().to_owned())
        .collect::<BTreeSet<_>>();
    let expected = COMMANDS
        .iter()
        .map(|command| format!("allow-{}", command.replace('_', "-")))
        .collect::<BTreeSet<_>>();
    assert_eq!(actual, expected);
    assert_eq!(capability["identifier"], "session-commands");
    assert_eq!(capability["windows"], serde_json::json!(["main"]));
    assert!(capability.get("remote").is_none());
}

#[test]
fn session_commands_are_declared_and_registered() {
    let build_script = include_str!("../build.rs");
    let source = include_str!("../src/lib.rs");
    let handlers = source
        .split("tauri::generate_handler![")
        .nth(1)
        .unwrap()
        .split("])")
        .next()
        .unwrap();
    for command in COMMANDS {
        assert!(
            build_script.contains(&format!("\"{command}\"")),
            "missing manifest command {command}"
        );
        assert!(
            handlers.contains(command),
            "missing invoke handler {command}"
        );
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("permissions/autogenerated")
            .join(format!("{command}.toml"));
        let permission = std::fs::read_to_string(path).unwrap();
        assert!(permission.contains(&format!("commands.allow = [\"{command}\"]")));
    }
}
