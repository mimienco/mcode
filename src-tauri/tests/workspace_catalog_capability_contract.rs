use serde_json::Value;
use std::collections::BTreeSet;

const COMMANDS: [&str; 4] = [
    "workspace_catalog_get",
    "workspace_pick_folder",
    "workspace_list_detected",
    "workspace_path_status",
];

#[test]
fn project_catalog_access_is_limited_to_the_primary_local_window() {
    let capability: Value = serde_json::from_str(include_str!(
        "../capabilities/workspace-catalog-commands.json"
    ))
    .unwrap();
    assert_eq!(capability["windows"], serde_json::json!(["main"]));
    assert!(capability.get("remote").is_none());
    let permissions: BTreeSet<_> = capability["permissions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|item| item.as_str().unwrap().to_owned())
        .collect();
    assert_eq!(
        permissions,
        COMMANDS
            .iter()
            .map(|command| format!("allow-{}", command.replace('_', "-")))
            .collect()
    );
    let handlers = include_str!("../src/lib.rs")
        .split("tauri::generate_handler![")
        .nth(1)
        .unwrap()
        .split("])")
        .next()
        .unwrap();
    for command in COMMANDS {
        assert!(include_str!("../build.rs").contains(&format!("\"{command}\"")));
        assert!(
            handlers.split(',').any(|entry| entry.trim() == command),
            "missing {command}"
        );
        let permission = std::fs::read_to_string(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("permissions/autogenerated")
                .join(format!("{command}.toml")),
        )
        .unwrap();
        assert!(permission.contains(&format!("commands.allow = [\"{command}\"]")));
    }
}
