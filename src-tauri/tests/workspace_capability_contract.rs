use serde_json::Value;
use std::collections::BTreeSet;

/// The three `workspace.session` commands (`parity-matrix.json` row
/// `workspace.session`) must be the ONLY permissions the workspace capability
/// grants — no default rules, mirrors window_capability_contract.rs.
#[test]
fn workspace_capability_grants_exactly_the_three_workspace_commands() {
    let capability: Value =
        serde_json::from_str(include_str!("../capabilities/workspace-commands.json")).unwrap();
    let permissions = capability["permissions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|permission| permission.as_str().unwrap())
        .collect::<BTreeSet<_>>();

    assert_eq!(
        permissions,
        BTreeSet::from([
            "allow-workspace-open",
            "allow-workspace-switch",
            "allow-workspace-list-recent",
        ])
    );
    assert_eq!(capability["identifier"], "workspace-commands");
    assert_eq!(capability["windows"], serde_json::json!(["main"]));
}

/// The build script's app manifest must declare all three commands — that
/// declaration is what makes tauri-build autogenerate the allow-*/deny-*
/// permission tomls (no default rule exists, so an undeclared command is
/// unreachable from the renderer).
#[test]
fn build_manifest_declares_the_three_workspace_commands() {
    let build_script = include_str!("../build.rs");

    for command in [
        "workspace_open",
        "workspace_switch",
        "workspace_list_recent",
    ] {
        assert!(
            build_script.contains(&format!("\"{command}\"")),
            "build.rs app manifest must declare {command}"
        );
    }
}

#[test]
fn autogenerated_permissions_exist_for_each_workspace_command() {
    for command in [
        "workspace_open",
        "workspace_switch",
        "workspace_list_recent",
    ] {
        // CTD: the test harness may run with either the workspace root or
        // src-tauri as CWD; resolve both spellings.
        let candidates = [
            format!("src-tauri/permissions/autogenerated/{command}.toml"),
            format!("permissions/autogenerated/{command}.toml"),
        ];
        let contents = candidates
            .iter()
            .find_map(|candidate| std::fs::read_to_string(candidate).ok())
            .unwrap_or_else(|| panic!("autogenerated {command}.toml must be committed"));
        assert!(
            contents.contains(&format!("commands.allow = [\"{command}\"]")),
            "autogenerated {command}.toml must allow {command}"
        );
    }
}
