//! Harness-injected turn classification + event-name normalization — Rust port
//! of `src/shared/harness-injected-user-turns.ts` and
//! `normalizeHookEventName` (`agent-hook-listener.ts:2277-2286`).

// We match only tags we have observed from harnesses, never a broad kebab
// shape: a real prompt starting with a custom `<my-element>` is a genuine user
// turn, and misclassifying it would hide the turn.
const KNOWN_HARNESS_TAG_NAMES: &[&str] = &[
    "agent-message",
    "bash-input",
    "bash-stderr",
    "bash-stdout",
    "command-args",
    "command-message",
    "command-name",
    "cross-session-message",
    "fork-boilerplate",
    "local-command-caveat",
    "local-command-stderr",
    "local-command-stdout",
    "mcp-polling-update",
    "mcp-resource-update",
    "system-reminder",
    "task-notification",
    "teammate-message",
    "user-memory-input",
    "user-prompt-submit-hook",
];

const COMPACT_CONTINUATION_PREFIX: &str =
    "this session is being continued from a previous conversation";
const HARNESS_INJECTED_TURN_PREFIXES: &[&str] = &[
    "<channel source=",
    "[request interrupted",
    "a message arrived from ",
    "another claude session sent a message",
    "no response requested.",
    "caveat: the messages below were generated by the user while running local commands",
    COMPACT_CONTINUATION_PREFIX,
];

const HARNESS_CLASSIFY_HEAD_LIMIT: usize = 256;
const HARNESS_CLASSIFY_LEADING_WS_LIMIT: usize = 64;

fn normalized_harness_turn_head(text: &str) -> String {
    let mut start = 0;
    let ws_scan_end = text.len().min(HARNESS_CLASSIFY_LEADING_WS_LIMIT);
    let bytes = text.as_bytes();
    while start < ws_scan_end && matches!(bytes[start], b' ' | b'\t' | b'\n' | b'\r' | 0x0c) {
        start += 1;
    }
    if start >= text.len() {
        return String::new();
    }
    super::fields::truncate_utf16(&text[start..], HARNESS_CLASSIFY_HEAD_LIMIT).to_lowercase()
}

/// True only for observed harness shapes; unknown kebab tags stay user turns.
pub fn is_known_harness_injected_user_turn_text(text: &str) -> bool {
    let normalized = normalized_harness_turn_head(text);
    if normalized.is_empty() {
        return false;
    }
    if let Some(rest) = normalized.strip_prefix('<') {
        let tag_end = rest
            .find(|ch: char| ch == '>' || ch.is_whitespace())
            .unwrap_or(rest.len());
        let tag_name = &rest[..tag_end];
        if is_kebab_tag(tag_name) && KNOWN_HARNESS_TAG_NAMES.contains(&tag_name) {
            return true;
        }
    }
    HARNESS_INJECTED_TURN_PREFIXES
        .iter()
        .any(|prefix| normalized.starts_with(prefix))
}

fn is_kebab_tag(tag: &str) -> bool {
    let bytes = tag.as_bytes();
    if bytes.is_empty() || !bytes[0].is_ascii_lowercase() {
        return false;
    }
    bytes[1..]
        .iter()
        .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || *b == b'-')
}

/// True only for the observed post-compaction continuation prompt.
pub fn is_compact_continuation_user_turn_text(text: &str) -> bool {
    normalized_harness_turn_head(text).starts_with(COMPACT_CONTINUATION_PREFIX)
}

/// `normalizeHookEventName` — CamelCase/snake/hyphen → snake lowercase.
pub fn normalize_hook_event_name(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    let chars: Vec<char> = value.trim().chars().collect();
    let mut separator_run = false;
    for (index, ch) in chars.iter().enumerate() {
        if ch.is_ascii_uppercase() {
            let prev_is_lower_alnum = index > 0
                && chars[index - 1].is_ascii_alphanumeric()
                && !chars[index - 1].is_ascii_uppercase();
            if prev_is_lower_alnum {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else if *ch == '-' || ch.is_whitespace() {
            if !separator_run {
                out.push('_');
            }
            separator_run = true;
            continue;
        } else {
            out.push(*ch);
        }
        separator_run = false;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_tags_classify_as_harness() {
        assert!(is_known_harness_injected_user_turn_text(
            "<system-reminder>hi"
        ));
        assert!(is_known_harness_injected_user_turn_text(
            "<task-notification>x"
        ));
        assert!(!is_known_harness_injected_user_turn_text("<my-element>x"));
        assert!(is_known_harness_injected_user_turn_text(
            "This session is being continued from a previous conversation"
        ));
        assert!(is_known_harness_injected_user_turn_text(
            "[request interrupted by user"
        ));
    }

    #[test]
    fn event_name_normalization() {
        assert_eq!(
            normalize_hook_event_name("PostToolUseFailure"),
            "post_tool_use_failure"
        );
        assert_eq!(normalize_hook_event_name("pre-llm-call"), "pre_llm_call");
        assert_eq!(
            normalize_hook_event_name("User Prompt Submit"),
            "user_prompt_submit"
        );
        assert_eq!(normalize_hook_event_name("pre__tool-use"), "pre__tool_use");
        assert_eq!(normalize_hook_event_name("pre - tool"), "pre_tool");
    }

    #[test]
    fn harness_head_truncation_handles_unicode_and_unclosed_known_tags() {
        assert!(!is_known_harness_injected_user_turn_text(&format!(
            "a{}",
            "😀".repeat(200)
        )));
        assert!(is_known_harness_injected_user_turn_text("<system-reminder"));
        assert!(!is_known_harness_injected_user_turn_text("<unknown-tag"));
    }
}
